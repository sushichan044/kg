"""Generate the upright-range table of Unicode Vertical_Orientation (UAX #50).

Usage:
    uv run scripts/gen-vertical-orientation.py --source path/to/VerticalOrientation.txt
    uv run scripts/gen-vertical-orientation.py --download   # fetch the pinned file

The input must match the pinned SHA-256. Code points whose value is U, Tu or Tr
are upright in `text-orientation: mixed`; every other code point is sideways (R).
"""

import argparse
import hashlib
from pathlib import Path
import re
import sys
import urllib.request

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "packages/core/src/composer/internal/vertical-orientation-table.ts"

UNICODE_VERSION = "17.0.0"
URL = f"https://www.unicode.org/Public/{UNICODE_VERSION}/ucd/VerticalOrientation.txt"
SHA256 = "dcef09c3fb24d356b042569c328ec341efc5b53447700d799f2fb4834c3cd3cd"

MAX_CODE_POINT = 0x10FFFF
UPRIGHT_VALUES = {"U", "Tu", "Tr"}
KNOWN_VALUES = UPRIGHT_VALUES | {"R"}

# Header lines such as "#         CJK-Related & Yi:                   U+2E80..U+A4CF"
DEFAULT_UPRIGHT = re.compile(r"^#\s+[^:]+:\s+U\+([0-9A-F]+)(?:\.\.U\+([0-9A-F]+))?\s*$")
DATA = re.compile(r"^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)\s*#")


def parse(text: str) -> list[bool]:
    """Return a per-code-point upright flag; unlisted code points default to R."""
    upright = [False] * (MAX_CODE_POINT + 1)

    in_defaults = False
    for line in text.splitlines():
        if "In the following list of explicit code points" in line:
            in_defaults = True
            continue
        if "All other code points, assigned and unassigned" in line:
            in_defaults = False
        match = DEFAULT_UPRIGHT.match(line) if in_defaults else None
        if match:
            start = int(match[1], 16)
            end = int(match[2] or match[1], 16)
            upright[start : end + 1] = [True] * (end - start + 1)

    entries = 0
    for line in text.splitlines():
        match = DATA.match(line)
        if not match:
            continue
        value = match[3]
        if value not in KNOWN_VALUES:
            raise SystemExit(f"unknown Vertical_Orientation value: {line}")
        start = int(match[1], 16)
        end = int(match[2] or match[1], 16)
        upright[start : end + 1] = [value in UPRIGHT_VALUES] * (end - start + 1)
        entries += 1
    if entries == 0:
        raise SystemExit("no data lines found")
    return upright


def to_ranges(upright: list[bool]) -> list[int]:
    """Flatten into [start0, end0, start1, end1, ...] (inclusive, sorted, merged)."""
    flat: list[int] = []
    start = None
    for code_point, flag in enumerate(upright):
        if flag and start is None:
            start = code_point
        elif not flag and start is not None:
            flat += [start, code_point - 1]
            start = None
    if start is not None:
        flat += [start, MAX_CODE_POINT]
    return flat


def render(flat: list[int]) -> str:
    pairs = [f"0x{flat[i]:X}, 0x{flat[i + 1]:X}," for i in range(0, len(flat), 2)]
    body = "\n".join(f"  {pair}" for pair in pairs)
    return f"""// Generated by scripts/gen-vertical-orientation.py. Do not edit.
// Source: {URL}
// SHA-256: {SHA256}

/**
 * Unicode {UNICODE_VERSION} の `Vertical_Orientation` が U・Tu・Tr のコードポイント範囲。
 * 閉区間 `[start, end]` を昇順に並べた平坦な配列で、範囲外はすべて R。
 */
export const UPRIGHT_RANGES: readonly number[] = [
{body}
];
"""


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--source", type=Path, help="local VerticalOrientation.txt")
    source.add_argument("--download", action="store_true", help=f"fetch {URL}")
    args = parser.parse_args()

    if args.download:
        with urllib.request.urlopen(URL) as response:
            data = response.read()
    else:
        data = args.source.read_bytes()

    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit(f"SHA-256 mismatch: expected {SHA256}, got {digest}")

    flat = to_ranges(parse(data.decode("utf-8")))
    OUTPUT.write_text(render(flat), encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(ROOT)} ({len(flat) // 2} ranges)")


if __name__ == "__main__":
    main()
